## Frequently Asked Questions

## Can I sell a house if I have an active lien from the city?
Yes, you can. A lien is essentially a legal claim against your property for unpaid debts—in this case, fines for code violations. When you sell the house, the lien is typically paid off out of the sale proceeds at the time of closing. If you sell to a cash buyer like me, we calculate the lien amount into our offer and handle the logistics of paying the city during escrow. It’s a seamless process for you, and it clears your name of the debt.

## Will the city force me to demolish unpermitted work?
In extreme cases, yes. If an addition is structurally unsound or encroaches on a neighbor''s property line (setback violations), the city may issue a "Notice to Abate," which can include demolition. However, most cities prefer "regularization"—which means bringing the work up to current codes and paying back-fees for the permits. This is often expensive and requires opening up walls for inspections. If you don''t have the cash for that, selling to a professional who can handle the construction is usually the best move.

