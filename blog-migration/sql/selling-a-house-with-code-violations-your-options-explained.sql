## Can a buyer get a mortgage on a house with code violations?
It depends on the severity. Minor issues like a missing handrail or a cracked window might pass a conventional loan inspection. However, "health and safety" violations—like a non-functional HVAC system, exposed wiring, or a roof with less than two years of life left—will usually disqualify the home for FHA, VA, or even standard conventional financing. This is why houses with major violations often sit on the market for months until a cash buyer comes along.

## How do I find out if my house has "hidden" violations?
The best way is to visit your local Building and Safety Department. You can request a "Permit History" or a "Freedom of Information Act" (FOIA) request for your address. This will show you every permit ever pulled, every inspection failed, and any outstanding "orders to comply." Be aware that "opening the sleeping dog" can sometimes alert the city to issues they hadn''t noticed yet, so many sellers prefer to have a professional buyer do this due diligence during a private sale.

## Is it better to lower my price or fix the violations myself?
This is a math problem. If the fix costs $10,000 but the violation is scaring away 90% of your buyers, you might have to drop your price by $30,000 to find someone willing to take the risk. If you have the time, expertise, and cash, fixing it yourself usually nets you the most money. But if you''re like most of the people I help—who are busy, stressed, or dealing with an inherited property—the "holding costs" (taxes, insurance, and interest) of waiting months to fix it often outweigh the profit of a DIY repair.

