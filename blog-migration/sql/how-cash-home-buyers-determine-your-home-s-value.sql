## The Investor’s Formula: The 70% Rule (Modified)

You might have heard of the "70% Rule" on TV. It’s a classic industry standard that says an investor should pay 70% of the ARV, minus repairs. 

**Formula: (ARV x 0.70) - Repairs = Maximum Allowable Offer (MAO)**

However, in high-demand markets like Southern California, that 70% often moves to 75% or even 80% because the margins are tighter and the demand is higher. 

Let''s do a quick example:
*   **ARV:** $600,000
*   **Repairs needed:** $75,000
*   **Formula (at 75%):** ($600,000 x 0.75) = $450,000
*   **Minus Repairs:** $450,000 - $75,000 = **$375,000 Offer**

Why the 25-30% haircut? That covers our profit, our risk, our holding costs, and the commissions we pay later. It’s the price of convenience and speed. You get your money in days, and I get a project that (hopefully) keeps my crew working.

