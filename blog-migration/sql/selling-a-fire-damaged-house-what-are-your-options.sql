## Can I sell a house while the insurance claim is still open?
Yes, you absolutely can, but it requires some specific paperwork. Usually, you would "assign the claim" to the buyer, or more commonly, you settle the "structure" portion of the claim yourself and then sell the property in its current state. The buyer takes the property as-is, and you keep the insurance proceeds for the loss of value. It’s a very common way to handle these transactions, especially for people who just want to move on with their lives. I’ve handled many deals where we closed escrow while the homeowner was still finalizing their personal property claim (for clothes, furniture, etc.) with their agent.

