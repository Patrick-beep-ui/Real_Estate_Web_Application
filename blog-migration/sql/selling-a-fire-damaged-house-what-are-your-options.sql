## Will a cash buyer really buy a house that’s completely gutted?
To a guy like me? A gutted house is actually a dream! When a house is stripped down to the studs, I can see exactly what I’m working with. There are no hidden surprises behind the drywall. If you have a fire-damaged property that has already been "demolitioned" or gutted by a remediation crew, it is very attractive to investors. We can see the electrical, the plumbing, and the structural framing clearly. So don''t feel like you have to put it back together to sell it. We buy "ugly" houses, and we definitely buy "burnt" houses.

## How do I get the smoke smell out before selling?
If you’re trying to sell the traditional way to a family, you *must* get the smell out. This usually involves professional "thermal fogging" or using ozone generators. You also have to seal the charred wood with a specific type of primer (like KILZ or BIN) that traps odors. However, if you sell to a professional cash buyer, you don''t need to do any of this. We have our own crews who specialize in heavy-duty remediation. You can save the $5,000 to $10,000 it costs for professional odor removal and just sell it as it stands.

## What if the city has condemned my house after the fire?
Don''t panic. A "condemned" or "red-tagged" status just means the building isn''t safe to inhabit *right now*. It doesn''t mean the land is worthless or that the house has to be torn down (though sometimes that is the best option). We buy red-tagged properties all the time. We work with the city building departments to pull the necessary permits, satisfy the safety requirements, and bring the building back up to code. If you''ve been red-tagged, selling for cash is often the easiest way to avoid the legal headaches of dealing with city code enforcement.

## Is fire damage worse than flood damage?
In my professional opinion, fire damage is often "cleaner" to fix than major flood damage, but it’s more expensive. Flood water brings in bacteria and can rot a foundation from the inside out. Fire damage is more about structural replacement and odor control. However, fire damage tends to scare away traditional buyers more than water damage does. From an investment standpoint, we look at both similarly: they are both "heavy lifts" that require a professional touch to restore correctly.

