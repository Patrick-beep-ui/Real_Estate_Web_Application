## Step 1: Immediate Actions After the Fire

Before we talk about selling, we have to talk about safety and logistics. If you’re looking to [sell your house fast in San Diego](/locations/san-diego-ca) or anywhere else after a fire, your first 48 hours are critical.

### Secure the Property
The last thing you need is a liability suit because someone wandered into your damaged home and got hurt. Board up the windows, tarp the roof, and put up a temporary fence. This also prevents looting—believe it or not, people do steal from fire-damaged sites.

### Contact Your Insurance Company
Do this immediately. Get a copy of your policy and look for "Loss of Use" coverage. This is a lifesaver—it often pays for your hotel and meals while your home is uninhabitable.

### Get the Fire Report
You’ll need the official report from the fire department to provide to buyers or insurance adjusters. It details the cause and the extent of the damage, which is vital for full disclosure when you eventually sell.

