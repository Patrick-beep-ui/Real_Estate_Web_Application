Here is some good news. When you inherit a house, you usually get a **"step-up in basis."** 

Let’s say your parents bought a house in [Orange County](/locations/orange-ca) for $50,000 in 1975. Today, it’s worth $1 million. If they sold it before they passed, they’d owe taxes on a massive gain. But because you inherited it, your "basis" becomes the value on the day they passed ($1 million). If you sell it for $1 million shortly after, you owe $0 in capital gains tax. This is a massive financial advantage that you need to discuss with your CPA.

