## Can I sell the house while it''s still in probate?
Yes, in many states, you can! This is called a "Probate Sale." You’ll need the court’s permission, and the buyer will often have to wait for a specific notice period (Notice of Proposed Action) to expire. It takes a bit more paperwork, but you don''t have to wait 12 months for probate to fully close before you find a buyer and get a contract signed.

## Do I have to clean out the house before selling to an investor?
If you sell to a traditional buyer on the MLS, yes—the house usually needs to be "broom clean." But if you sell to a company like mine, the answer is no. We’ve bought houses full of old furniture, clothes, and even old cars. We tell our sellers: "Take what you want, leave what you don''t." We handle the haul-away so you don''t have to spend your weekends at the dump.

## What are the tax implications if I sell for more than the appraised value?
If the house was appraised at $500,000 when your loved one passed, and you sell it six months later for $520,000, you only owe capital gains tax on the $20,000 difference—not the full $520,000. This is why getting a professional appraisal immediately after the death is so important; it "sets the bar" for your tax liability.

## How do I handle a house that has a reverse mortgage?
Reverse mortgages can be tricky. When the owner passes, the loan becomes due immediately. Usually, the lender gives the heirs 6 months to either pay off the loan or sell the property. If you’re in this spot, you need to move fast. If there’s equity left, you want to sell before the bank starts the foreclosure process. We help families with reverse mortgage situations all the time by providing a quick cash exit before the bank takes over.

