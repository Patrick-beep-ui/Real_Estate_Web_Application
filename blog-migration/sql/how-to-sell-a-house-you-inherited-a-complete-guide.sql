## FAQ: Everything You’re Afraid to Ask

## What if there are multiple heirs and we don''t agree?
This is the most common "nightmare" scenario. If one sibling wants to sell and the other wants to keep the house, it can lead to a **Partition Action**. This is a legal move where a judge orders the sale of the property so the proceeds can be split. It’s expensive and burns bridges. My advice? Sit down with a neutral third party or a mediator first. Usually, the sibling who wants to keep the house can buy out the others, but they’ll need to qualify for a mortgage to do so.

