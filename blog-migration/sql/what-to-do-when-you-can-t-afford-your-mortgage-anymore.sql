## What happens to my equity if the bank forecloses?
This is the saddest part of my job. If the bank forecloses and sells your house at auction for $400,000, but you only owed $300,000, you are *technically* entitled to the "surplus funds." However, getting that money back from the county or the bank can take years and require expensive lawyers. Often, the bank’s legal fees and late penalties eat up all that equity anyway. Selling the home yourself before the auction is the only way to guarantee you keep your equity.

## Do I have to move out immediately if I sell to a cash buyer?
One of the biggest benefits of working with a private buyer like me is flexibility. When you sell on the traditional market, the buyer usually wants to move in the day of closing. When I buy a house, we can negotiate a "post-occupancy" agreement. This means I can give you the cash for your house, and you can stay there for a few extra weeks while you pack and find your next place. We want to make the transition as stress-free as possible.

## Is it better to file for bankruptcy or sell the house?
I’m a real estate expert, not a bankruptcy attorney, but here’s what I’ve seen: Bankruptcy is a temporary band-aid. It can stop a foreclosure sale for a few weeks or months, but it doesn''t make the debt go away. It also wreaks havoc on your credit for up to 10 years. Selling the house provides a permanent solution. You get rid of the debt, save your credit from a foreclosure hit, and often put cash in your pocket to start over.

