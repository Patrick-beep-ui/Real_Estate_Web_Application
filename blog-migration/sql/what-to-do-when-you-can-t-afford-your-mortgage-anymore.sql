## Step 2: Call Your Lender Immediately

This is the part everyone hates. You think the bank is the "bad guy" waiting to kick you out. In reality, banks are in the business of lending money, not owning and managing real estate. They *hate* foreclosing because it costs them a fortune in legal fees.

When you call, ask to speak to the **Loss Mitigation Department**. This is the team specifically designed to help people who can''t pay. Here are the three main things they might offer:

### Forbearance
This is a temporary pause or reduction in your payments. It’s great if you have a short-term crisis (like an injury), but remember: you still owe the money. It usually gets tacked onto the back of the loan or requires a lump sum later.

### Loan Modification
This is where the bank actually changes the terms of your loan to make the payment affordable. They might lower the interest rate or extend the term from 30 years to 40 years. I’ve seen this save families in [Irvine](/locations/irvine-ca) who just needed a $400 reduction to breathe again.

### Repayment Plan
If you missed a few payments but are back on your feet, they can spread those missed payments over the next 6-12 months.

## Step 3: Understand the "Short Sale" Escape Hatch

If a loan modification isn''t an option and you owe more than the house is worth, a short sale might be your best bet. 

In a short sale, the bank agrees to let you sell the home for *less* than what you owe on the mortgage. Why would they do that? Because it’s still cheaper for them than a full foreclosure. 

I did a lot of work with short sales early in my career. They take time and require a lot of paperwork, but they save your credit score from the "nuclear bomb" that is a foreclosure. If you''re looking to [sell your house fast in Oakland](/locations/oakland-ca) and you''re underwater on your loan, this is a path we should discuss.

