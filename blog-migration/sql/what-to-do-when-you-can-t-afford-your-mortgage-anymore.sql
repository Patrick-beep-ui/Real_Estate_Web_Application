## Frequently Asked Questions

## How many payments can I miss before foreclosure starts?
In most cases, the formal foreclosure process doesn''t begin until you are 120 days (4 months) delinquent. This is a federal law. However, your lender will start sending "Notice of Intent to Foreclose" much sooner. Once you hit that 120-day mark, the bank can record a Notice of Default (NOD), which is the first official step in taking your home. You want to have your solution—whether it''s a modification or a sale—in place *before* that 120-day window closes.

## Will selling my house for cash hurt my credit?
Quite the opposite! If you sell your house and pay off your mortgage in full, it shows up as "Paid in Full" or "Satisfied" on your credit report. This is actually a positive signal to future lenders. Even if you sell for a bit less than market value to get a fast cash exit, the fact that the debt was settled voluntarily is much better than a foreclosure, which can drop your credit score by 100 to 150 points and stay on your record for seven years.

## Can I sell my house if I’m already in foreclosure?
Yes, you absolutely can! Until the moment the "gavel falls" at the auction, you still own the home. This is called the "Right of Redemption" period. I have helped many homeowners [sell their house fast in Anaheim](/locations/anaheim-ca) just days before the auction. We work with the bank to get a "payoff demand," and our cash clears the debt. The foreclosure is stopped, the bank is happy, and you walk away without a foreclosure on your record.

