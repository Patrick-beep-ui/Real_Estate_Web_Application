## FAQ: Everything You’re Afraid to Ask

### 1. How much money can I actually save by not using a realtor?
On a typical **$500,000** home, a realtor''s commission is usually 5-6%, which is **$25,000 to $30,000**. By selling it yourself or to a cash buyer, you can keep a huge chunk of that. Even if you pay a 2.5% commission to a buyer’s agent, you’re still saving **$12,500 to $15,000**. That’s a lot of money that could be going toward your next down payment or your retirement.

### 2. Can I sell my house "As-Is" without making any repairs?
Absolutely. In fact, that’s exactly what I do on **Flip or Flop**. When you sell "As-Is," you are telling the buyer that you won''t be making any repairs or giving credits for issues found during the inspection. This is the fastest way to sell, but you have to price it accordingly. Investors like me love buying "As-Is" because we have the crews to fix things up, but a family looking for a "turn-key" home will likely pass.

### 3. How do I handle the closing process?
In California, you’ll work with a Title and Escrow company. Once you and the buyer sign the Purchase Agreement, you open escrow. They will handle the title search (to make sure there are no liens on the property), the transfer of the deed, and the distribution of funds. It’s much simpler than most people think. You just need to provide them with your mortgage payoff information and sign the final closing docs.

### 4. What if my house needs a lot of work?
If your house has foundation issues, mold, or major structural problems, a traditional buyer won''t be able to get a loan from a bank. Banks are very picky about the condition of the collateral. In these cases, you almost *have* to sell to a cash buyer or an investor. We don''t care about the mold or the cracked foundation—we look at what the house *can* be, not what it is today.

### 5. Is it safe to sell my house to a "We Buy Houses" company?
It can be, but you have to do your homework. There are a lot of "wholesalers" out there who will tie up your property and then try to sell the contract to someone else. You want to work with someone who has a track record. Look for a company with a real office, a history of closed deals, and someone who is willing to show you their proof of funds. I’ve built my entire career on being transparent and doing what I say I’m going to do.

