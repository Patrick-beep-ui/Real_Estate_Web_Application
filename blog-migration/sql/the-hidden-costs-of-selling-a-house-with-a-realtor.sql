## Do I have to fix everything the inspector finds?
Technically, no. A home sale is a negotiation. However, in a traditional sale, if you refuse to fix major items (like a leaky roof or outdated electrical), the buyer has the right to back out and take their earnest money with them. Worse, once a problem is "disclosed" in an inspection report, you are legally required to tell the next potential buyer about it. This gives the buyer a lot of leverage. This is why many people prefer selling "as-is" to a cash buyer—we take on the risk of the repairs so you don’t have to.

## Is the 6% commission negotiable?
Yes, commissions are always negotiable by law. However, keep in mind that the commission is usually split between the listing agent’s brokerage and the buyer’s agent’s brokerage. If you negotiate the commission too low, buyer’s agents might be less motivated to show your home to their clients. It’s a frustrating "pay to play" system that exists in the traditional market. When you sell directly to a cash buyer, there are zero commissions because there are no agents involved in the transaction.

## What are "Holding Costs" and why do they matter?
Holding costs are the expenses you pay every single day you own the property. This includes your mortgage interest, property taxes (which are high in California!), insurance, utilities, and maintenance. If your house sits on the market for 90 days and takes another 30 to close, that’s four months of payments. If your monthly carry is $4,000, that’s $16,000 out of your pocket. Most people don''t realize that a "fast" sale at a slightly lower price can actually net you more money than a "slow" sale at a higher price because of these holding costs.

## Can I sell my house with a Realtor if it needs major repairs?
You can, but it’s difficult. Most traditional buyers are looking for a "turn-key" home because they are using FHA or conventional loans that have strict habitability requirements. If your house has a foundation issue, mold, or a bad roof, a bank may refuse to lend on it. This limits your pool of buyers to investors anyway. If your house needs work, listing it with a Realtor often leads to months of frustration and multiple failed escrows before you finally find a buyer who can actually close.

