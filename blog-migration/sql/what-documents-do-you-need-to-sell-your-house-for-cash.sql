When I’m looking at a potential flip for *Flipping 101*, I want to know the history of the bones of the house.

### Records of Repairs and Renovations
Did you put on a new roof in 2018? Did you upgrade the HVAC in 2021? Keep those receipts! Even in a "as-is" cash sale, showing me that you’ve maintained the property helps me give you the strongest possible offer. It shows pride of ownership.

### Warranty Information
If that new roof has a 20-year transferable warranty, that adds value. Make sure you have those certificates ready to hand over to the new owner.

### Utility Bills
Sometimes, a cash buyer will ask for the last few months of utility bills. This helps us estimate holding costs while we’re doing the renovation. If you want to [sell your house fast in Long Beach](/locations/long-beach-ca), having a folder with your water, gas, and electric bills ready shows you’re a serious, organized seller.

## 4. Disclosure Documents: Honesty is the Best Policy

In California, you are legally required to disclose certain things about the property, even in a cash sale. 

### Transfer Disclosure Statement (TDS)
This is where you tell us about any known issues. Does the basement leak when it rains? Is there a crack in the foundation? **Be honest.** I’ve bought thousands of houses in terrible condition—I’m not afraid of repairs! What I don’t like are surprises. Disclosing everything upfront protects you legally and keeps the deal moving.

### Natural Hazard Disclosure (NHD) Report
In our neck of the woods, we have to worry about fires, floods, and earthquakes. Most sellers order an NHD report to show if the property is in a high-risk zone.

## 5. Specific Situations: Probate, Trust, and Divorce

Life happens. A lot of the folks I work with are selling because of a major life change. These situations require a few extra pieces of paper:

*   **Death Certificate:** If a co-owner has passed away.
*   **Trust Documents:** If the house is held in a trust, we need the "Certification of Trust" to see who has the legal authority to sign the papers.
*   **Probate Letters:** If the house is in probate, the court will issue "Letters Testamentary" or "Letters of Administration." 
*   **Divorce Decree:** If the sale is part of a divorce settlement, the decree will outline how the proceeds should be split.

## 4 Common Mistakes I See Sellers Make

![An aerial drone photograph of a high-end coastal neighborhood, showing a grid of well-maintained homes with swimming poo](https://mcgzyxrozhogzmohyfos.supabase.co/storage/v1/object/public/blog-images/what-documents-do-you-need-to-sell-your-house-for-cash/image-2-1779811264738.png)


I’ve seen it all. I’ve seen deals fall apart over a missing signature and I’ve seen sellers lose money because they didn''t have their paperwork ready. Here are the big ones to avoid:

1.  **Waiting to find the Deed:** Don''t wait until you have an offer to look for your title paperwork. If there is a "cloud" on the title (like an old lien from a contractor that was never cleared), it can take weeks to fix. Start now.
2.  **Hiding Issues:** I can''t stress this enough. If you try to hide a termite infestation or a plumbing leak, it *will* come out during the inspection or title search. It’s much better to be upfront so we can factor it into the price from day one.
3.  **Not Checking for "Zombie" Liens:** Sometimes, a mortgage you paid off years ago still shows up as active because the bank forgot to file the "Satisfaction of Mortgage." Check your title report early!
4.  **Forgetting the Keys and Remotes:** It sounds silly, but gather all the keys, garage door openers, and even the codes for the smart thermostat. It makes the handoff so much smoother.

