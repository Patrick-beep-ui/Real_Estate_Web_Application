### ## What if I can''t find my original deed?
Don''t sweat it. It happens more often than you think. Your local County Recorder’s office keeps a record of every land transaction. You can usually go down there (or go online) and request a certified copy for a small fee. If you’re working with me to [sell your house fast in San Diego](/locations/san-diego-ca), my title team can actually help you track this down. We have resources to find almost any document related to the property’s history.

### ## Are the requirements different for an inherited property?
Yes, they are. If you inherited the house, the most important document is the one that proves you have the legal right to sell it. If the property went through probate, we need the court documents. If it was in a trust, we need the trust agreement. Inheriting a house can be an emotional rollercoaster, and the last thing you want to deal with is a mountain of legal forms. That’s why we work closely with estate attorneys to make sure everything is handled correctly and respectfully.

### ## Do I need to make repairs before I gather these documents?
Absolutely not. When I say "as-is," I mean it. I’ve walked into houses with holes in the ceiling, outdated kitchens from the 70s, and overgrown yards that look like jungles. You don''t need to pick up a hammer or a paintbrush. Your "document" for repairs is simply the disclosure form where you tell me what’s broken. I’ll take it from there. My team and I love a good project—it’s what we do on *Flip or Flop* every single day!

### ## How long does the paperwork process take?
If you have the documents I listed above ready to go, we can often close in as little as 7 days. The longest part of the process is usually waiting for the title company to do their "title search" to make sure there are no hidden liens. If you’re organized and responsive, we can move lightning fast. I’ve had situations where we started the conversation on a Monday and the seller had their cash by the following Tuesday.

### ## Is a cash offer legally binding?
Once both parties sign the Purchase and Sale Agreement, it is a legally binding contract. This document outlines the price, the closing date, and any contingencies (though with my cash offers, we try to keep those to a minimum). This is why it’s so important to work with a buyer you trust. I’ve built my entire career on my reputation. When I make an offer, I stand by it. I’m not here to play games or change the price at the last minute.

