## 1. The Foundation: Proof of Identity and Ownership

Before we can talk numbers, we have to talk identity. It sounds basic, but you’d be surprised how many deals get delayed because of an expired ID or a name change that wasn''t recorded properly.

### Government-Issued ID
You’ll need a valid driver’s license, state ID, or passport. If you’re selling a property in a different city—let’s say you’re trying to [sell your house fast in Stockton](/locations/stockton-ca) but you live in SoCal—make sure your ID is current.

### The Original Sales Contract
This is the document from when *you* originally bought the house. It helps title companies track the history of the property. If you can’t find it, don''t panic—the county recorder’s office usually has a copy, but having it on hand saves us days of research.

### The Deed
This is the big one. The deed is the legal document that transfers ownership. Whether it’s a Grant Deed or a Quitclaim Deed, we need to see who is currently on the title. If you’re selling a house after a divorce or the passing of a loved one, this is where things can get tricky.

## 2. Financial Documents: What Do You Owe?

To give you a clean cash offer, we need to know exactly what needs to be paid off at the closing table. 

### Mortgage Payoff Statement
Even if you’re selling for cash, your existing mortgage has to be paid off first. You’ll need to call your lender and request a "Payoff Letter." This isn''t just your current balance; it includes the interest calculated to the exact day of closing.

### Property Tax Records
In California, property taxes are a big deal. Whether you''re looking to [sell your house fast in Los Angeles](/locations/los-angeles-ca) or San Diego, we need to ensure the taxes are current. If you’re behind, that’s okay! We can usually pay those out of the sale proceeds, but we need the statements to know the exact amount.

### Homeowners Association (HOA) Documents
If your property is part of an HOA, I need the contact info for the association and a copy of the current dues. We also need to know if there are any outstanding "special assessments." I’ve seen $20,000 assessments pop up at the last minute for roof repairs or pool upgrades—getting these documents early prevents those "gotcha" moments.

## 3. The "Paper Trail" of the Property

