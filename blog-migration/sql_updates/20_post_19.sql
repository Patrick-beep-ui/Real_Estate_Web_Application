## FAQ: Everything You Need to Know About Selling As-Is

## Does selling "as-is" mean I''ll get a lowball offer?
Not necessarily. While you won''t get the same price as a fully renovated, "turn-key" home, a fair as-is offer takes into account the cost of repairs, the risk the buyer is taking, and the speed of the transaction. When I buy a house in [Riverside](/locations/riverside-ca), I look at the "After Repair Value" (ARV) and subtract the costs. You’re paying for convenience and certainty. You avoid Realtor commissions (usually 6%), closing costs, and the months of waiting. Often, the net amount in your pocket is very similar to a traditional sale without any of the work.

## Can I sell a house as-is if it has a mortgage?
Absolutely. This is one of the most common questions I get. When you sell the house—whether to a traditional buyer or an investor—the escrow company will use the sale proceeds to pay off your existing mortgage balance in full. Any money left over is yours to keep. If you owe more than the house is worth (being "underwater"), we can often discuss a short sale, but for most people, an as-is sale is a clean way to clear the debt and move on.

