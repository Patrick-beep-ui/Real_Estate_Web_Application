I care about the **Return on Investment.**

If you spend $10,000 on a kitchen refresh, does it add $10,000 to your sale price? If it only adds $8,000, you just paid $2,000 for the "privilege" of doing construction work. That’s a bad deal.

### High-ROI Repairs (The "Must-Dos")
If you are going to do repairs, focus on these three areas. They almost always pay for themselves:
1.  **Curb Appeal:** First impressions are everything. A $500 landscaping cleanup and a fresh coat of paint on the front door can add $5,000 in perceived value.
2.  **Neutral Paint:** If your walls are neon green or covered in scuffs, spend the money on a neutral "Greige." It makes the space look larger and cleaner.
3.  **Light Fixtures:** Swapping out dated, "boob-style" ceiling lights for modern LEDs is cheap and changes the entire vibe of a room.

### Low-ROI Repairs (The "Money Pits")
Avoid these unless the house is literally unlivable:
*   **Full Kitchen Remodels:** Unless the cabinets are falling off the wall, a full gut job rarely returns 100% of the cost for a retail seller.
*   **Swimming Pools:** I love a good pool party, but adding a pool to sell a house is a losing game. It costs $50k-$100k and might only add $20k in value.
