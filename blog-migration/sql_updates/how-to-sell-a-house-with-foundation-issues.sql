## Step 1: Identifying the Red Flags

Before you panic, you need to know what you’re actually looking at. Not every crack is a structural nightmare. Some are just "settling," which is normal. But if you see these, it’s time to pay attention:

1.  **Horizontal Cracks:** If you see horizontal cracks in your basement walls or foundation, that’s often hydrostatic pressure pushing in. That’s a "call a pro" moment.
2.  **Stair-Step Cracks:** These usually appear in brick or cinder block. They mean the house is settling unevenly.
3.  **The Door Test:** If your doors are sticking or there are gaps at the top, the frame is out of square because the ground underneath has shifted.
4.  **Uneven Floors:** If you feel like you’re walking uphill in your own hallway, your slab or pier-and-beam system has moved.

