## How long does foundation repair take?
The actual work is faster than you’d think. Most piering jobs can be done in 3 to 7 days. However, the engineering and permitting process can take 4 to 8 weeks depending on your city. If you’re in a rush to [sell your house fast in Santa Ana](/locations/santa-ana-ca), you need to factor in that lead time.

## Should I tell my Realtor about the cracks?
Yes, 100%. Your Realtor has a legal and ethical obligation to disclose material facts. If you keep them in the dark, you’re putting them—and yourself—at massive legal risk. A good agent will know how to frame the issue to potential buyers so it doesn''t sound like the end of the world.

## How do I know if the repair was done right?
Always ask for a "transferable warranty." Any reputable foundation company will guarantee their work for 20+ years, and that warranty should move to the new owner. This is a huge selling point! Also, ensure the final "elevation report" shows the house is back within industry tolerances (usually 1/10th of an inch).

