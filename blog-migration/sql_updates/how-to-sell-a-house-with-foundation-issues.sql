## FAQ: Everything You’re Afraid to Ask

## Does a foundation issue mean my house is worthless?
Absolutely not. No house is worthless. It just means the "market value" is adjusted. If a house would be worth $500,000 in perfect condition, and it needs $50,000 in foundation work, it’s likely worth around $400,000 to $425,000 in its current state. Investors look for these opportunities because we know how to handle the risk.

## Can I get a mortgage on a house with foundation problems?
It’s very tough. Traditional lenders (FHA, VA, Conventional) have "minimum property standards." If an appraiser sees a structural crack, they’ll usually flag it for "repair before closing." This is why most houses with foundation issues are sold to cash buyers. If your buyer is using a loan, be prepared for the bank to say "no" at the last minute.

## Will my homeowners insurance cover foundation repair?
Usually, the answer is no. Most policies exclude "earth movement" or "settlement." Insurance typically only kicks in if the foundation was damaged by something sudden and accidental, like a pipe bursting under the slab. If it’s just the house settling over time, you’re likely on the hook for the bill.

